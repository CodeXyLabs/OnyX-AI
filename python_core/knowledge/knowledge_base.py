def _stem(word):
    """Простой русский стеммер: убирает типовые окончания."""
    if len(word) <= 4:
        return word
    for suf in ("ую", "ие", "ия", "ии", "её", "ой", "ая", "яя", "ый", "ий", "ое",
                "ем", "ом", "ах", "ях", "ов", "ев", "ей", "ь", "а", "я",
                "о", "е", "у", "ю", "ы", "и", "й"):
        if word.endswith(suf) and len(word) - len(suf) >= 3:
            return word[:-len(suf)]
    return word


def search_facts(question, limit=6):
    """Возвращает релевантные факты и их темы для запроса (простой лексический поиск)."""
    q = question.lower()
    # нормализация: «ё» -> «е» для лучшего совпадения
    qn = q.replace("ё", "е")
    words = [w for w in qn.replace("?", "").replace("!", "").replace(",", " ").replace(".", " ").split() if len(w) > 1]
    # добавляем синонимическую подсказку по совпадению основ слов
    hints = set()
    for hint, topic in TOPIC_HINTS.items():
        hint = hint.lower().replace("ё", "е")
        hit = False
        if hint in qn:
            hit = True
        else:
            # сравниваем основы (чтобы «нейросети» совпало с «нейросеть» и т.п.)
            hstem = _stem(hint)
            if len(hstem) >= 4:
                for qw in words:
                    if _stem(qw) == hstem or (len(qw) >= 4 and hstem in qw):
                        hit = True
                        break
        if hit:
            # не даём «сеть» срабатывать внутри «нейросеть»
            if hint == "сеть" and "нейро" in qn:
                continue
            hints.add(topic)

    # Слова, которые часто дают ложные срабатывания (сеть -> сети вместо нейросети)
    STOP_WORDS = {"что", "как", "такое", "это", "про", "для", "его", "она", "они", "ещё",
                  "работает", "работа", "является", "используют", "используется",
                  "помогают", "помогает", "может", "можно", "нужно", "есть", "называется"}

    scored = []
    for topic, facts in KNOWLEDGE_BASE:
        topic_score = 0
        tl = topic
        if tl in qn:
            topic_score += 4
        if topic in hints:
            # если тема указана подсказкой — сильный приоритет
            topic_score += 8
        for fact in facts:
            fl = fact.lower().replace("ё", "е")
            score = topic_score
            matched_words = 0
            for w in words:
                if w in STOP_WORDS:
                    continue
                if " " + w + " " in " " + fl + " ":
                    score += 4
                    matched_words += 1
                else:
                    # морфологическая нормализация: сравниваем основы слов
                    ws = _stem(w)
                    if len(ws) >= 4 and ws in fl:
                        score += 2
                        matched_words += 1
            if score > 0:
                scored.append((score, matched_words, topic, fact))

    scored.sort(key=lambda x: (-x[0], -x[1]))
    # если есть темы-подсказки, отбрасываем факты из «соседних» тем с малым весом
    if hints:
        hint_topics = set(hints)
        max_hint_score = max((s for s, _, t, _ in scored if t in hint_topics), default=0)
        scored = [(s, m, t, f) for s, m, t, f in scored if (t in hint_topics) or (s >= max_hint_score * 0.6)]
    out = []
    seen = set()
    for score, matched, topic, fact in scored:
        if fact in seen:
            continue
        seen.add(fact)
        out.append({"topic": topic, "fact": fact, "score": score})
        if len(out) >= limit:
            break
    return out


