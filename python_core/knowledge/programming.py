def _stem_ru(word):
    """Грубая нормализация: усечение частых окончаний для сравнения основ."""
    if len(word) <= 4:
        return word
    for suf in ("иями", "ями", "ами", "ого", "ему", "ией", "ия", "ие", "ий", "ый",
                "ая", "яя", "ое", "ее", "ов", "ев", "ах", "ях", "ом", "ем", "ой",
                "ую", "юю", "ть", "ет", "ит", "ут", "ют", "а", "я", "ы", "и", "о", "е", "у", "ю", "ь"):
        if word.endswith(suf) and len(word) - len(suf) >= 3:
            return word[:-len(suf)]
    return word


def detect_languages(question):
    q = " " + question.lower().replace("ё", "е") + " "
    found = []
    for lang, keys in LANGUAGES.items():
        for k in keys:
            if k in ("go ",) and " go " not in q:
                continue
            if k.strip() and k.strip() in q:
                found.append(lang)
                break
    return found


def _kw_hit(kw, q, q_stems):
    """Проверяет попадание ключевого слова с учётом словоформ.

    Возвращает силу совпадения: 0 — нет, 1 — по основе, 2 — точное вхождение.
    """
    if not kw:
        return 0
    if kw in q:
        return 2 if (" " in kw or len(kw) >= 5) else 1
    parts = [p for p in kw.split() if len(p) > 1]
    if parts and all(_stem_ru(p) in q_stems for p in parts):
        return 2 if len(parts) > 1 else 1
    ks = _stem_ru(kw)
    if len(ks) >= 4 and ks in q_stems:
        return 1
    return 0


def lookup_programming(question, limit=2, threshold=5):
    """Ищет наиболее подходящую запись базы знаний по программированию.

    Возвращает список {"topic","title","answer","code","score"} или [].
    """
    q = " " + str(question or "").lower().replace("ё", "е") + " "
    q = q.replace("?", " ").replace("!", " ").replace(",", " ").replace(".", " ")
    words = [w for w in q.split() if len(w) > 2]
    if not words:
        return []

    q_stems = {_stem_ru(w) for w in words if len(w) > 2}
    langs = set(detect_languages(question))
    scored = []

    for entry in PROGRAMMING:
        score = 0.0
        strong = False
        text = (entry["title"] + " " + entry["answer"]).lower().replace("ё", "е")

        for kw in entry["keywords"]:
            hit = _kw_hit(kw, q, q_stems)
            if hit == 2:
                score += 6
                strong = True
            elif hit == 1:
                score += 3
                # короткие узнаваемые аббревиатуры (jwt, gIL, api) — тоже сильный сигнал
                if len(kw) <= 5:
                    score += 2
                    strong = True

        for w in words:
            if len(w) < 4:
                continue
            if w in text:
                score += 0.8
            else:
                ws = _stem_ru(w)
                if len(ws) >= 5 and ws in text:
                    score += 0.5

        if entry["topic"] in langs:
            score += 3

        if strong and score >= threshold:
            scored.append((score, entry))

    if not scored:
        return []

    scored.sort(key=lambda x: -x[0])
    out = []
    seen_titles = set()
    for score, entry in scored:
        if entry["title"] in seen_titles:
            continue
        seen_titles.add(entry["title"])
        out.append({
            "topic": entry["topic"],
            "title": entry["title"],
            "answer": entry["answer"],
            "code": entry["code"],
            "score": round(score, 2),
        })
        if len(out) >= limit:
            break
    return out


def programming_context(question, limit=1):
    """Готовый текстовый контекст для промпта модели."""
    hits = lookup_programming(question, limit=limit)
    if not hits:
        return ""
    parts = []
    for h in hits:
        parts.append(h["answer"])
        if h["code"]:
            parts.append("Пример:\n" + h["code"])
    return "\n\n".join(parts)


def programming_stats():
    topics = sorted({e["topic"] for e in PROGRAMMING})
    return {"entries": len(PROGRAMMING), "topics": len(topics), "topic_list": topics}
